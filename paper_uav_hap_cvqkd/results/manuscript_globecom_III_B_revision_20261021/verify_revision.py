"""Verify document/data preservation without compilation or scientific calls."""
from pathlib import Path
import csv
import hashlib
import json
import re
import zipfile
import fitz

OUT=Path(__file__).resolve().parent
ROOT=OUT.parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(path):
    with path.open(encoding='utf-8',newline='') as stream:
        return list(csv.DictReader(stream))


def main():
    checks=[]
    def check(name, condition):
        assert condition, name
        checks.append(name)
    sealed=(OUT/'validation/final_receipt.json').exists()
    if sealed:
        receipt=json.loads((OUT/'validation/final_receipt.json').read_text())
        for member,digest in receipt['artifact_sha256'].items():
            check('sealed artifact '+member,sha(OUT/member)==digest)
    tex=(OUT/'main.tex').read_text(encoding='utf-8')
    base=(ROOT/'results/manuscript_ieee_overleaf_20261021/main.tex').read_text(encoding='utf-8')
    original=base.split(r'\section{Optimization Problem}',1)[0]
    prefix=(OUT/'validation/protected_prefix_revised.tex.txt').read_text(encoding='utf-8')
    recovered=prefix
    edits=json.loads((OUT/'validation/heading_edits.json').read_text())
    for before,after in reversed(edits):
        check('heading replacement unique '+before[:35],recovered.count(after)==1)
        recovered=recovered.replace(after,before,1)
    check('prefix science and frontmatter identical after reversing headings',recovered==original)
    check('assembled prefix agrees',tex.startswith(prefix))
    check('bibliography unchanged',tex[tex.index('% Generated by IEEEtran.bst'):]==base[base.index('% Generated by IEEEtran.bst'):])
    check('body assembled from current revision', (OUT/'revised_sections.tex').read_text(encoding='utf-8') in tex)
    sections=re.findall(r'\\section\{([^}]+)\}',tex)
    check('automatic section order I to V',sections==[
        'HAP--UAV CV-QKD System and Problem Formulation','Recorded Physical-Layer Model',
        'SKR Performance Analysis',r'Numerical Results \& Discussions','Conclusions'])
    subsections=re.findall(r'\\subsection\{([^}]+)\}',tex)
    check('III.B follows III.A',subsections[-2:]==['Recorded Rate and Security Boundary','SKR Performance Optimization'])
    check('no section counter override',r'\setcounter{section}' not in tex)
    labels=re.findall(r'\\label\{([^}]+)\}',tex)
    check('unique labels',len(labels)==len(set(labels)))
    for label in re.findall(r'\\(?:eqref|ref)\{([^}]+)\}',tex):
        check('defined reference '+label,label in labels)
    for label in ['eq:raw','eq:p1','eq:p2','eq:p3','eq:dp_init','eq:dp','eq:greedy','alg:dp']:
        check('retained formula/algorithm label '+label,label in labels)
    bibkeys=re.findall(r'\\bibitem\{([^}]+)\}',tex)
    for keys in re.findall(r'\\cite(?:\[[^\]]*\])?\{([^}]+)\}',tex):
        for key in keys.split(','):
            check('defined citation '+key,key in bibkeys)
    stack=[]
    for kind,env in re.findall(r'\\(begin|end)\{([^}]+)\}',tex):
        if kind=='begin':
            stack.append(env)
        else:
            check('balanced environment '+env,bool(stack) and stack.pop()==env)
    check('all environments closed',not stack)
    for path in re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}',tex):
        check('figure exists '+path,(OUT/path).is_file())
    check('one column and one wide figure',tex.count(r'\begin{figure}[t]')==1 and tex.count(r'\begin{figure*}[t]')==1)
    check('compact DP algorithm included',r'\begin{algorithm}[t]' in tex)
    body=(OUT/'revised_sections.tex').read_text(encoding='utf-8')
    for forbidden in [r'\vspace{-',r'\hspace{-',r'\geometry',r'\tiny',r'\scriptsize',r'\setlength{\textheight}']:
        check('no artificial compression '+forbidden,forbidden not in body)
    points=read_csv(OUT/'data/plotted_points.csv')
    check('57 saved means plotted',len(points)==57)
    for p in points:
        source=read_csv(OUT/'data'/p['source_csv'])
        members=[r for r in source if r['metric']==p['metric'] and r['method']==p['method'] and r['x']==p['x']]
        check('exact saved point '+p['output_panel']+p['method']+p['x'],len(members)==1 and all(p[k]==v for k,v in members[0].items()))
    def point(filename,metric,method,x):
        return float(next(r['y'] for r in read_csv(OUT/'data'/filename) if r['metric']==metric and r['method']==method and float(r['x'])==x))
    cloud='fig2_cloud_blockage_data.csv';cand='fig1_candidate_positions_data.csv';temp='fig3_temporal_correlation_data.csv'
    for method,expected in [('Stationary',24.60),('Greedy',16.53),('DP',4.07)]:
        check('cloud endpoint '+method,round(point(cloud,'unavailability_percent',method,.8),2)==expected)
    gain=100*(point(cand,'U','DP',100)/point(cand,'U','DP',10)-1)
    check('J objective gain 11.409 percent',round(gain,3)==11.409)
    check('rho distance endpoints',round(point(temp,'D','DP',0),2)==1038.25 and round(point(temp,'D','DP',.98),2)==31.84)
    tradeoff=[r for r in read_csv(OUT/'data/fig4_skr_mobility_tradeoff_data.csv') if r['method']=='DP']
    zero=next(r for r in tradeoff if float(r['lambda_bits_per_use'])==0)
    representative=next(r for r in tradeoff if float(r['lambda_bits_per_use'])==9.468026677248516e-6)
    check('distance reduction 88.370 percent',round(100*(1-float(representative['x'])/float(zero['x'])),3)==88.370)
    check('usable-rate reduction 0.515 percent',round(100*(1-float(representative['y'])/float(zero['y'])),3)==.515)
    for x,expected in [(0,23.712),(.98,.155)]:
        gain=100*(point(temp,'U','DP',x)/point(temp,'U','Stationary',x)-1)
        check('rho objective gain '+str(x),round(gain,3)==expected)
    findings=json.loads((OUT/'data/verified_findings.json').read_text())
    for method,metric,digits,expected in [('Stationary','K',2,4.16),('Greedy','K',2,2.70),('Stationary','U',2,3.07),('Greedy','U',2,4.42)]:
        check('default gain '+method+metric,round(findings['default_gain_percent'][method][metric],digits)==expected)
    rendered=[]
    for name,expected_width in [('fig2_cloud_unavailability.pdf',3.48*72),('fig3_parameter_sensitivity.pdf',7.14*72)]:
        d=fitz.open(OUT/'figures'/name)
        check('vector figure dimensions '+name,len(d)==1 and abs(d[0].rect.width-expected_width)<.1)
        check('figure is vector '+name,not d[0].get_images() and bool(d[0].get_text()) and bool(d[0].get_drawings()))
        check('figure font embedded '+name,all(len(d.extract_font(font[0])[3])>0 for font in d[0].get_fonts()))
        sizes=[span['size'] for block in d[0].get_text('dict')['blocks'] if block['type']==0 for line in block['lines'] for span in line['spans']]
        rendered.append(dict(figure=name,minimum_font_points=min(sizes),native_width_points=d[0].rect.width))
    config=json.loads((OUT/'data/manuscript_mobility.json').read_text())
    expected=dict(wavelength_m=1.55e-6,full_divergence_rad=233e-6,receiver_diameter_m=.08,h_HAP_m=20000,h_UAV_m=1000)
    check('requested optical configuration',all(config['optical'][k]==v for k,v in expected.items()))
    check('geometry table',config['geometry']['h_hap_m']==20000 and config['geometry']['h_uav_m']==1000 and config['geometry']['grid_side_m']==1000 and config['geometry']['grid_cells_per_side']==10)
    check('security table',config['security']['beta']==.95 and config['security']['xi_ch']==.0186 and config['security']['R']==1 and config['security']['xi_det']==0)
    check('mission table',config['mission']==dict(slots=30,slot_duration_s=20,max_speed_m_per_s=15))
    check('cloud table',config['cloud']['probability']==.4 and config['cloud']['correlation_length_m']==250 and config['cloud']['temporal_rho']==.9 and config['cloud']['realizations']==100)
    check('reference distance table',config['optimization']['reference_distance_m']==1000)
    check('security and lifecycle retained',all(s in tex for s in ['UNVALIDATED\\_SECURITY\\_MODEL','NOT\\_READY\\_FOR\\_PUBLICATION\\_SCALE\\_RUNS']))
    for p,digest in json.loads((OUT/'input_manifest.json').read_text()).items():
        check('input preserved '+p,sha(Path(p))==digest)
    snapshot=json.loads((OUT/'startup_manifest.json').read_text())
    changed=[]
    permitted={'docs/EVIDENCE.md','docs/PROJECT_STATE.md','docs/NEXT_ACTIONS.md','.agent/SESSION_HANDOFF.md'}
    for p,digest in snapshot['protected_sha256'].items():
        if sha(ROOT/p)!=digest:
            changed.append(p)
            check('only relevant ledgers changed '+p,p in permitted)
    with zipfile.ZipFile(OUT/'overleaf_III_B_revision.zip') as z:
        check('ZIP intact',z.testzip() is None)
        for member in ['main.tex','figures/fig2_cloud_unavailability.pdf','figures/fig3_parameter_sensitivity.pdf']:
            check('ZIP exact '+member,z.read(member)==(OUT/member).read_bytes())
    result=dict(status='CURRENTLY_VERIFIED_PASS',scope='STATIC_LATEX_SAVED_DATA_VECTOR_FIGURES_ONLY',
        checks=len(checks),check_names=checks,plotted_means=len(points),figure_fonts=rendered,
        protected_files=len(snapshot['protected_sha256']),changed_ledgers=changed,
        compilation='NOT_RUN_BY_EXPLICIT_USER_CHOICE',compiled_pdf_visual_review='NOT_RUN',
        occupied_page_length='NOT_MEASURED',scientific_evaluations=0,
        historical_text_provenance='CRLF-only differences recorded separately; no raw-hash equivalence asserted',
        security_status='UNVALIDATED_SECURITY_MODEL',lifecycle='NOT_READY_FOR_PUBLICATION_SCALE_RUNS')
    if not sealed:
        (OUT/'validation/static_checks.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k not in ['check_names','figure_fonts']}))


if __name__=='__main__':
    main()
